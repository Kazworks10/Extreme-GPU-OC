#!/usr/bin/env python3
"""Compile src/bench/shaders/stress.comp to SPIR-V and write kernel_spv.inc.

Usage: python3 tools/gen_spirv.py [path/to/glslangValidator]

The generated file is committed so building gpuoc needs no shader compiler.
"""
import hashlib
import pathlib
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "bench" / "shaders" / "stress.comp"
OUT = ROOT / "src" / "bench" / "kernel_spv.inc"


def main() -> int:
    tool = sys.argv[1] if len(sys.argv) > 1 else shutil.which("glslangValidator")
    if not tool:
        print("glslangValidator not found", file=sys.stderr)
        return 1
    with tempfile.TemporaryDirectory() as tmp:
        spv = pathlib.Path(tmp) / "stress.spv"
        subprocess.run([tool, "-V", "--target-env", "vulkan1.1", "-o", str(spv), str(SRC)], check=True)
        data = spv.read_bytes()
    words = struct.unpack("<%dI" % (len(data) // 4), data)
    digest = hashlib.sha256(SRC.read_bytes()).hexdigest()
    lines = [
        "// Generated by tools/gen_spirv.py from src/bench/shaders/stress.comp. Do not edit.",
        f"// source sha256: {digest}",
    ]
    for i in range(0, len(words), 8):
        lines.append("  " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(words)} words)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
